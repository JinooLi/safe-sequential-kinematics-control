"""Generate slide dots from the same plan used to verify the talk order."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
plan = json.loads((ROOT / 'evidence/story_plan.json').read_text())
parts = plan['progress_parts']
covered = [page for part in parts
           for page in range(part['first_page'], part['last_page'] + 1)]
assert covered == list(range(2, plan['main_slides'] + 1))
groups = '\n'.join(
    rf"  \defense@group{{{p['name']}}}{{{p['first_page']}}}{{{p['last_page']}}}%"
    for p in parts)
(ROOT / 'progress-data.tex').write_text(
    '% Generated by scripts/build_progress_data.py from evidence/story_plan.json.\n'
    '% One dot per main slide; the cover and backup slides are excluded.\n'
    '\\newcommand{\\DefenseProgressGroups}{%\n' + groups + '\n}\n')
print(f'Generated {len(covered)} slide dots in {len(parts)} groups.')
